"""Markdown tables and the checked-in baseline keys for a scan result."""
from __future__ import annotations


def baseline_keys(result: dict) -> set[str]:
    """profile|host|kind|name for every non-parked unbound call (what a new unbound call is compared against)."""
    keys = set()
    for row in result["rows"]:
        if row["ground_only"]:
            continue
        for profile in row["per_profile"]:
            keys.add(f"{profile}|{row['host']}|{row['kind']}|{row['name']}")
    return keys


def _cell(profile: dict | None) -> str:
    if not profile:
        return ""
    return f"{profile['call_sites']}/{profile['scripts_blocked']}"


def _table(rows: list[dict], profile_ids: list[str], limit: int | None = None) -> list[str]:
    head = ["Function", "Kind", "Status", "Severity", "Timing", "Mods"] + profile_ids
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    for row in rows[:limit]:
        cells = [f"`{row['name']}`", row["kind"], row["status"], row["severity"], row["timing"], str(row["mods_blocked_count"])]
        cells += [_cell(row["per_profile"].get(p)) for p in profile_ids]
        out.append("| " + " | ".join(cells) + " |")
    return out


def _available(result: dict) -> list[dict]:
    return [p for p in result["profiles"] if p.get("available")]


SEVERITY_ORDER = {"critical": 4, "high": 3, "medium": 2, "low": 1, "parked": 0}


def _impact_key(row: dict, profile: str | None = None):
    cell = row["per_profile"].get(profile) if profile else None
    direct = cell["scripts_blocked_directly"] if cell else row["total_scripts_directly"]
    sites = cell["call_sites"] if cell else row["total_call_sites"]
    severity = cell["severity"] if cell else row["severity"]
    return (-SEVERITY_ORDER[severity], -row["mods_blocked_count"], -direct, -sites, row["host"], row["name"])


def _impact_table(rows: list[dict], profile: str | None, limit: int) -> list[str]:
    head = ["#", "Host", "Function", "Kind", "Status", "Severity", "Timing", "Call sites", "Scripts calling it", "Mods blocked"]
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    for number, row in enumerate(sorted(rows, key=lambda r: _impact_key(r, profile))[:limit], 1):
        cell = row["per_profile"].get(profile) if profile else None
        sites = cell["call_sites"] if cell else row["total_call_sites"]
        direct = cell["scripts_blocked_directly"] if cell else row["total_scripts_directly"]
        severity = cell["severity"] if cell else row["severity"]
        timing = cell["timing"] if cell else row["timing"]
        out.append(f"| {number} | {row['host']} | `{row['name']}` | {row['kind']} | {row['status']} | {severity} | "
                   f"{timing} | {sites} | {direct} | {row['mods_blocked_count']} |")
    return out


def summary_markdown(result: dict, config: dict) -> str:
    profiles = _available(result)
    ids = [p["id"] for p in profiles]
    galactic = [r for r in result["rows"] if not r["ground_only"] and r["lane"] == "gc"]
    lines = ["# Lua API coverage (generated)", "",
             "Generated by `python -m tools.lua_api_scan`. Each cell is `call sites / scripts blocked`. "
             "Ground-battle-only calls are parked and not listed. The full table with call-site detail is the scan's JSON output.",
             "**Static versus runtime.** The scan executes no Lua and runs no game. Which scripts belong to which host, which "
             "functions a host binds, and when a call runs (load, start, recurring) are inferred from file paths, XML, the C++ "
             "registration sites and a call graph, so a row is a candidate gap, not an observed failure. The only runtime facts "
             "are the lines of the 'Runtime cross-check' table, which come from a live game log triage (2026-11-19) and are not "
             "generated by the scan. Limits: `tools/lua_api_scan/README.md`, section Limits.",
             "",
             "Object scripts are an upper bound: every GameObject script an XML file names, while the runtime attaches only "
             "the types that exist as galactic fleets or planets. Hosts owned by the tactical lane list demand only.",
             "", "## Owner stack: top 15 galactic gaps", ""]
    for profile in (p for p in profiles if p.get("owner_stack")):
        rows = [r for r in galactic if profile["id"] in r["per_profile"]]
        lines += [f"{profile['title']} (`{profile['id']}`): severity first, then scripts that call the function themselves.", ""]
        lines += _impact_table(rows, profile["id"], 15)
    lines += ["", "## Ranked by mods blocked (all galactic hosts)", ""]
    lines += _impact_table(galactic, None, 40)
    lines += ["", "## Profiles", "", "| Profile | Title | Scripts | Script roots by host |", "|---|---|---|---|"]
    for p in profiles:
        roots = ", ".join(f"{h} {n}" for h, n in p["script_roots"].items())
        lines.append(f"| {p['id']} | {p['title']} | {p['scripts']} | {roots} |")
    lines += ["", "## Hosts read", "", "| Host | Lane | Bound globals | Bound methods | Stubbed names |", "|---|---|---|---|---|"]
    for host_id, summary in result["hosts"].items():
        lines.append(f"| {host_id} | {next((h['lane'] for h in config['hosts'] if h['id'] == host_id), '')} | "
                     f"{summary['bound_globals']} | {summary['bound_members']} | {summary['stubbed_names']} |")
    for host_id in result["hosts"]:
        host_rows = [r for r in result["rows"] if r["host"] == host_id and not r["ground_only"]]
        lines += ["", f"## {host_id}: unbound ({len(host_rows)})", ""]
        lines += _table(host_rows, ids, 60) if host_rows else ["None."]
    lines += ["", "## Runtime cross-check", "", "| Name | Kind | Static result | Hosts |", "|---|---|---|---|"]
    for item in result["runtime_crosscheck"]:
        lines.append(f"| `{item['name']}` | {item['kind']} | {item['static']} | {', '.join(item.get('hosts', [])) or item.get('explain', '')} |")
    return "\n".join(lines) + "\n"


def full_markdown(result: dict, config: dict) -> str:
    profiles = _available(result)
    ids = [p["id"] for p in profiles]
    lines = [summary_markdown(result, config).rstrip("\n"), "", "## Ground-battle only (parked)", ""]
    parked = [r for r in result["rows"] if r["ground_only"]]
    lines += _table(parked, ids, 80) if parked else ["None."]
    lines += ["", "## Unresolved callables (not registered engine API, not defined by a required script)", "",
              "| Host | Kind | Name | Call sites per profile |", "|---|---|---|---|"]
    for row in result["unresolved"][:150]:
        lines.append(f"| {row['host']} | {row['kind']} | `{row['name']}` | "
                     + ", ".join(f"{p} {n}" for p, n in sorted(row["per_profile"].items())) + " |")
    lines += ["", "## Demand on hosts whose reader belongs to another lane", "",
              "| Host | Kind | Name | Call sites per profile |", "|---|---|---|---|"]
    for row in result["demand_for_unread_hosts"][:200]:
        lines.append(f"| {row['host']} | {row['kind']} | `{row['name']}` | "
                     + ", ".join(f"{p} {n}" for p, n in sorted(row["per_profile"].items())) + " |")
    return "\n".join(lines) + "\n"

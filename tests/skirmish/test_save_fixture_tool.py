"""tools/replay/skirmish_save_fixture.py: the committed small save is taken from a test log only when it is exact."""
from __future__ import annotations

import base64
import hashlib
import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("skirmish_save_fixture", ROOT / "tools/replay/skirmish_save_fixture.py")
tool = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tool)


def line(data: bytes, digest: str | None = None) -> str:
    return (f"682: SKIRMISH-SAVE-FIXTURE-BYTES,sha256={digest or hashlib.sha256(data).hexdigest()},"
            f"base64={base64.b64encode(data).decode()}\n")


def test_the_one_printed_save_is_returned():
    data = bytes(range(256)) + b"EAWRCKP"
    log = "Start 682: skirmish_save_fixture\n" + line(data) + line(data) + "682: FAIL: the committed save equals\n"
    assert tool.fresh_save(log) == data


@pytest.mark.parametrize("log, message", [
    ("no save here\n", "0 different"),
    (line(b"one") + line(b"two"), "2 different"),
    (line(b"save", "0" * 64), "SHA-256"),
])
def test_missing_ambiguous_or_damaged_saves_are_refused(log, message):
    with pytest.raises(ValueError, match=message):
        tool.fresh_save(log)


def test_the_committed_save_is_pinned_for_publishing():
    import json
    config = json.loads((ROOT / "tools/publish_scan/config.json").read_text(encoding="utf-8"))
    relative = "tests/skirmish/fixtures/saves/tactical-v2-host.eawr-ckp"
    save = ROOT / relative
    if not save.exists():
        pytest.skip("the committed save is generated by the first pool build (skirmish_save_fixture)")
    assert config["assets"]["binary_allowlist"][relative] == hashlib.sha256(save.read_bytes()).hexdigest()
    assert relative in config["assets"]["binary_allowlist_origins"]
